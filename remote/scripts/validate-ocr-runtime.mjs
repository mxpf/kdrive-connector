// Explicit synthetic-only validation. Local workerd/SQLite DO; optional real AI
// binding via Wrangler's temporary development proxy. Never deploys the app.
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { build } from 'esbuild';
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';

const args = process.argv.slice(2);
const arg = key => args.includes(key) ? args[args.indexOf(key) + 1] : undefined;
const live = args.includes('--live');
assert.ok(arg('--report'), 'Supply a --report path.');
assert.ok(!live || (args.includes('--free-plan-verified') && /^[a-f0-9]{32}$/.test(arg('--account') ?? '')), 'Live binding requires verified Free plan and --account.');
assert.ok(!args.includes('--cancel-only') || live, '--cancel-only requires --live.');
const root = fileURLToPath(new URL('../../', import.meta.url));
const temp = await mkdtemp(join(tmpdir(), 'kdrive-ocr-runtime-'));
const dir = arg('--fixtures') ? resolve(arg('--fixtures')) : join(temp,'fixtures');
if (!arg('--fixtures')) {
  // Generate locally from committed source; accept no user documents.
  try {
    execFileSync(process.env.KDRIVE_TEST_PYTHON ?? 'python3',[join(root,'test/fixtures/ocr/generate.py'),dir],{stdio:['ignore','ignore','pipe'],timeout:120000});
  } catch {
    await rm(temp,{recursive:true,force:true});
    throw new Error('Synthetic fixture generation failed. Check Python dependencies and pdftoppm; no inference was attempted.');
  }
}
const manifest = JSON.parse(await readFile(join(dir, 'manifest.json'), 'utf8'));
const recorded = JSON.parse(await readFile(join(root, 'docs/evidence/ocr-checkbox-2026-10-13.json'), 'utf8'));
assert.equal(manifest.syntheticOnly, true);
// External fixture directories must match reviewed byte pins. Fresh fixtures
// are generated by this process from committed code (encryption uses randomness).
const fixtures = await Promise.all(recorded.cases.map(async row => {
  const meta = manifest.cases.find(c => c.name === row.name);
  assert.equal(meta.file, `${row.name}.pdf`);
  const bytes = await readFile(join(dir, meta.file));
  const sha256=createHash('sha256').update(bytes).digest('hex');
  if(arg('--fixtures')) assert.equal(sha256, row.sha256, `Unreviewed fixture ${row.name}`);
  return { ...meta, bytes: bytes.toString('base64'), sha256 };
}));
const report = { date: new Date().toISOString(), syntheticOnly: true, liveBinding: live,
  fixtureSource:arg('--fixtures')?'reviewed_byte_pins':'generated_in_process',
  deploymentPerformed: false, productionLimitsVerified: false, cases: [], faultChecks: [] };
let session, mf, ws;
let outbound = 0;
const save = () => writeFile(resolve(arg('--report')), JSON.stringify(report, null, 2) + '\n');
try {
  let connection;
  if (live) {
    const config = join(temp, 'wrangler.json');
    await writeFile(config, JSON.stringify({ name: 'kdrive-ocr-binding-validation', account_id: arg('--account'),
      compatibility_date: '2026-08-13', ai: { binding: 'AI', remote: true } }));
    const { maybeStartOrUpdateRemoteProxySession } = await import('wrangler');
    session = (await maybeStartOrUpdateRemoteProxySession({ path: config }))?.session;
    assert.ok(session, 'Missing remote development proxy.');
    connection = session.remoteProxyConnectionString;
  }
  const bundle = await build({ stdin: { contents: `
    import { DurableObject } from 'cloudflare:workers';
    import { Buffer } from 'node:buffer';
    import { readKDrivePdf } from './src/pdf-tools.ts';
    import { renderPdfOcrPage } from './src/pdf-render.ts';
    import { cloudflareOcrProvider, runPdfOcr } from './src/pdf-ocr.ts';
    import wasm from './pdfium.wasm';
    const fixtures = ${JSON.stringify(fixtures)};
    export class PdfTest extends DurableObject {
      async fetch(request) {
        const { name, mode = 'offline' } = await request.json();
        const fixture = fixtures.find(f => f.name === name);
        if (!fixture) return new Response('Unknown synthetic case', {status:400});
        const bytes = new Uint8Array(Buffer.from(fixture.bytes, 'base64'));
        const telemetry = { calls:0, aborted:false };
        const cancellation = new AbortController();
        const client = {
          resolveBinaryVersion:async()=>({file:{id:7,name:fixture.file,size:bytes.length},versionId:'synthetic-v1'}),
          downloadVersionStream:async()=>new Response(bytes),
        };
        const binding = {run:async(model,input,options)=>{
          telemetry.calls++;
          options?.signal?.addEventListener('abort',()=>{telemetry.aborted=true;},{once:true});
          if (mode==='hang') return new Promise(()=>{});
          if (mode==='quota') throw new Error('SYNTHETIC_PRIVATE_DETAIL: daily quota exceeded');
          if (mode==='offline') return {choices:[{message:{role:'assistant',content:'MOCK TRANSCRIPTION'},finish_reason:'stop'}]};
          if (!['live','live-cancel'].includes(mode)) throw new Error('Unknown mode');
          // Deliberately short, test-only deadline, started at binding invocation.
          if (mode==='live-cancel') setTimeout(()=>cancellation.abort(),100);
          const result = await this.env.AI.run(model,input,options);
          telemetry.responseKeys = Object.keys(result);
          telemetry.usage = result.usage ?? result.result?.usage;
          return result;
        }};
        try {
          const runtime = {render:(b,p,pw,o)=>renderPdfOcrPage(b,p,pw,o,wasm),provider:cloudflareOcrProvider(binding)};
          if (mode==='live-cancel') {
            const result=await runPdfOcr(runtime,bytes,1,fixture.password,cancellation.signal,fixture.ocrOptions);
            return Response.json({result,telemetry});
          }
          const result = await readKDrivePdf(client,42,{path:'/Synthetic/'+fixture.file,ocr:true,
            expectedSha256:fixture.sha256,password:fixture.password,...fixture.ocrOptions},runtime);
          return Response.json({result,telemetry});
        } catch(e) {return Response.json({errorCode:e.code,message:e.message,telemetry},{status:422});}
      }
    }
    export default {fetch(request,env){return env.PDF.getByName('synthetic').fetch(request);}};
  `, resolveDir: root }, bundle:true,write:false,format:'esm',platform:'neutral',conditions:['browser'],external:['node:*','cloudflare:*','*.wasm'],minify:true });
  const start = performance.now();
  mf = new Miniflare(convertV4MiniflareOptions({ name:'ocr-validation', port:0, inspectorPort:0,
    modules:[{type:'ESModule',path:'index.mjs',contents:bundle.outputFiles[0].text},
      {type:'CompiledWasm',path:'pdfium.wasm',contents:await readFile(join(root,'node_modules/@hyzyla/pdfium/dist/pdfium.wasm'))}],
    compatibilityDate:'2026-08-13',compatibilityFlags:['nodejs_compat'],
    durableObjects:{PDF:{className:'PdfTest',useSQLite:true}},
    ...(live ? {ai:{binding:'AI',remoteProxyConnectionString:connection}} : {}),
    outboundService:()=>{outbound++;return new Response('Unexpected network',{status:502});},
  }));
  const url = (await mf.ready).origin;
  report.localReadyWallMs = Math.round(performance.now()-start);
  // Initialize the isolate before requesting its inspector metrics.
  const cold = performance.now();
  const warmup = await fetch(url,{method:'POST',body:JSON.stringify({name:'unknown'})});
  assert.equal(warmup.status,400);
  report.localColdRequestWallMs = Math.round(performance.now()-cold);
  const inspector = new URL('/json/list', await mf.getInspectorURL());
  inspector.protocol = 'http:';
  const targets = await (await fetch(inspector)).json();
  const target = targets.find(t => t.title.includes('ocr-validation')) ?? targets[0];
  assert.ok(target?.webSocketDebuggerUrl, 'Local inspector target required.');
  ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((res,rej)=>{ws.onopen=res;ws.onerror=rej;});
  let next=0;
  const pending=new Map();
  ws.onmessage=event=>{const m=JSON.parse(event.data);const p=pending.get(m.id);if(p){pending.delete(m.id);m.error?p.reject(new Error(m.error.message)):p.resolve(m.result);}};
  const cdp=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;
    const timer=setTimeout(()=>{pending.delete(id);reject(new Error('Inspector timed out: '+method));},10000);
    pending.set(id,{resolve:v=>{clearTimeout(timer);resolve(v);},reject:e=>{clearTimeout(timer);reject(e);}});
    ws.send(JSON.stringify({id,method,params}));});
  report.heapBefore = await cdp('Runtime.getHeapUsage');
  await cdp('Profiler.enable');
  const invoke = async (name,mode) => {
    const begin=performance.now();
    const response=await fetch(url,{method:'POST',body:JSON.stringify({name,mode}),signal:AbortSignal.timeout(55000)});
    return {name,mode,httpStatus:response.status,wallMs:Math.round(performance.now()-begin),...await response.json()};
  };
  // Live calls are bounded to four fixtures, or two cancellation/recovery calls.
  const cases=args.includes('--cancel-only') ? [] : live ? ['scan','forms-reversed','forms-stale','encrypted-scan'] : fixtures.map(f=>f.name);
  for (const name of cases) {
    await cdp('Profiler.start');
    const row=await invoke(name,live?'live':'offline');
    const {profile}=await cdp('Profiler.stop');
    const nodes=new Map(profile.nodes.map(n=>[n.id,n.callFrame.functionName]));
    row.localSampledActiveMs=(profile.samples??[]).reduce((sum,id,i)=>sum+(['(idle)','(program)'].includes(nodes.get(id))?0:(profile.timeDeltas?.[i]??0)),0)/1000;
    row.heapAfter=await cdp('Runtime.getHeapUsage');
    report.cases.push(row);await save();
    assert.equal(row.httpStatus,200,`${name}: ${row.errorCode}`);
    assert.equal(row.telemetry.calls,1);
    assert.equal(row.result.sha256,fixtures.find(f=>f.name===name).sha256);
    if(live){
      const norm=s=>s.normalize('NFC').replace(/[\s*\x60]+/g,' ').trim().toLowerCase();
      row.missingText=fixtures.find(f=>f.name===name).expected.filter(s=>!norm(row.result.ocr.text).includes(norm(s)));
      assert.deepEqual(row.missingText,[],name);
    }
    console.log(JSON.stringify({case:name,status:'passed',wallMs:row.wallMs,localSampledActiveMs:row.localSampledActiveMs}));
  }
  if (!live) {
    const quota=await invoke('scan','quota');report.faultChecks.push(quota);
    assert.equal(quota.errorCode,'PDF_OCR_FAILED');assert.equal(quota.telemetry.calls,1);
    assert.ok(!JSON.stringify(quota).includes('SYNTHETIC_PRIVATE_DETAIL'));
    const hanging=invoke('scan','hang');
    await new Promise(r=>setTimeout(r,1000));
    const busy=await invoke('scan','offline');report.faultChecks.push(busy);
    assert.equal(busy.errorCode,'PDF_BUSY');assert.equal(busy.telemetry.calls,0);
    const timeout=await hanging;report.faultChecks.push(timeout);
    assert.equal(timeout.errorCode,'PDF_TIMEOUT');assert.equal(timeout.telemetry.calls,1);
    assert.equal(timeout.telemetry.aborted,true);assert.ok(timeout.wallMs>=44500&&timeout.wallMs<50000);
    const recovered=await invoke('scan','offline');report.faultChecks.push(recovered);
    assert.equal(recovered.httpStatus,200);assert.equal(recovered.telemetry.calls,1);
  }
  if (args.includes('--cancel-only')) {
    const cancelled=await invoke('scan','live-cancel');report.faultChecks.push(cancelled);await save();
    assert.equal(cancelled.errorCode,'PDF_TIMEOUT');assert.equal(cancelled.telemetry.calls,1);
    assert.equal(cancelled.telemetry.aborted,true);assert.ok(cancelled.wallMs<5000);
    const recovered=await invoke('scan','live');report.faultChecks.push(recovered);
    assert.equal(recovered.httpStatus,200);assert.equal(recovered.telemetry.calls,1);
    assert.equal(recovered.result.sha256,fixtures.find(f=>f.name==='scan').sha256);
    assert.match(recovered.result.ocr.text,/CEDAR-4826/);
  }
  // No forced GC: workerd does not implement every DevTools heap operation.
  // These are sampled diagnostic sizes, never a peak or full native-memory cap.
  report.heapAfter=await cdp('Runtime.getHeapUsage');
  report.unexpectedOutboundRequests=outbound;
  assert.equal(outbound,0);
  report.status='passed';
} catch(error) {
  report.status='failed';report.failure=error.message;
  console.error(JSON.stringify({status:'failed',message:error.message}));
  process.exitCode=1;
} finally {
  ws?.close();await mf?.dispose();await session?.dispose();
  await save();await rm(temp,{recursive:true,force:true});
}
