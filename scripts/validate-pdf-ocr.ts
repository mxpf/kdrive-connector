/** Explicit synthetic-only acceptance runner. Default mode never calls a model.
 * Generate fixtures with test/fixtures/ocr/generate.py first. Live mode requires
 * --live --free-plan-verified --account ID and an existing Wrangler login.
 * Credentials stay in memory; only Cloudflare's fixed API origin receives them.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, basename, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { readKDrivePdf } from '../src/pdf-tools.js';
import { renderPdfPage } from '../src/pdf-render.js';
import { cloudflareOcrProvider } from '../src/pdf-ocr.js';
import { missingOcrText } from './lib/ocr-acceptance.js';

const args = process.argv.slice(2);
const value = (key: string) => args[args.indexOf(key) + 1];
const root = resolve(fileURLToPath(new URL('../', import.meta.url)));
const live = args.includes('--live');
if (!args.includes('--fixtures')) throw new Error('Supply --fixtures DIRECTORY generated by test/fixtures/ocr/generate.py.');
const directory = resolve(value('--fixtures'));
if (live && (!args.includes('--free-plan-verified') || !args.includes('--account') || !/^[a-f0-9]{32}$/.test(value('--account')))) {
  throw new Error('Live tests require a verified Workers Free account: --free-plan-verified --account ID. No account upgrade is performed.');
}
const manifest = JSON.parse(await readFile(join(directory, 'manifest.json'), 'utf8'));
const allowed = ['scan','rotated','mixed','small-print','multilingual','forms','encrypted-scan'];
if (!manifest.syntheticOnly || !Array.isArray(manifest.cases) || manifest.cases.length !== allowed.length
  || manifest.cases.some((x: any) => !allowed.includes(x.name) || x.file !== `${x.name}.pdf` || basename(x.file) !== x.file)
  || new Set(manifest.cases.map((x:any)=>x.name)).size !== allowed.length) throw new Error('Invalid synthetic fixture manifest.');
let token: string | undefined;
if (live) {
  try {
    const credentials = JSON.parse(execFileSync(process.execPath, [join(root,'remote/node_modules/wrangler/bin/wrangler.js'),'auth','token','--json'], {
      cwd:join(root,'remote'), env:{...process.env,WRANGLER_SEND_METRICS:'false'}, encoding:'utf8', stdio:['ignore','pipe','pipe'],timeout:30000,
    }));
    if (typeof credentials.token !== 'string' || !credentials.token) throw new Error('Missing token');
    token = credentials.token;
  } catch { throw new Error('Cloudflare credentials unavailable. Sign in with Wrangler; no credential details are printed.'); }
}
const report: any = { date: new Date().toISOString(), live, syntheticOnly:true, calls:0, cases:[], deploymentPerformed:false };
const reportPath = join(directory, live ? 'live-report.json' : 'local-report.json');
for (const fixture of manifest.cases) {
  const bytes = new Uint8Array(await readFile(join(directory,fixture.file)));
  const start = performance.now();
  const row: any = { name:fixture.name, byteLength:bytes.length };
  report.cases.push(row);
  let wire: any;
  try {
    // Offline preparation renders pages, but never pretends mocked text is OCR.
    const provider = live ? cloudflareOcrProvider({ run: async (model, input, options) => {
      report.calls++;
      const response = await fetch(`https://api.cloudflare.com/client/v4/accounts/${value('--account')}/ai/run/${model}`, {
        method:'POST', headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'}, body:JSON.stringify(input), signal:options?.signal,
        redirect:'error',
      });
      const body = await response.json() as any;
      const output = body.result?.result ?? body.result;
      wire = { httpStatus:response.status, finishReason:output?.finish_reason, metrics:output?.metrics,
        usage:body.result?.usage, errorCodes:body.errors?.map((e:any)=>e.code), answer:output?.answer,
        // Synthetic-only evidence: preserve the actual model contract for review.
        result:body.result };
      if (!response.ok || body.success === false) throw new Error(`Cloudflare inference HTTP ${response.status}`);
      return body.result;
    } }) : undefined;
    const client = {
      resolveBinaryVersion:async()=>({file:{id:7,name:fixture.file,type:'file',size:bytes.length},versionId:'synthetic-v1'}),
      downloadVersionStream:async()=>new Response(bytes),
    };
    const result = await readKDrivePdf(client,42,{path:`/Synthetic OCR Acceptance/${fixture.file}`,password:fixture.password,ocr:live},provider ? {
      provider,render:async(data,page,password)=>{
        const image=await renderPdfPage(data,page,password);
        await writeFile(join(directory,`${fixture.name}-connector.png`),image.png);
        return image;
      },
    }:undefined);
    if (!live) {
      const image=await renderPdfPage(bytes,1,fixture.password);
      await writeFile(join(directory,`${fixture.name}-connector.png`),image.png);
      row.image={width:image.width,height:image.height,bytes:image.png.length};
    }
    row.sha256=result.sha256; row.textLayer=result.pages[0].text; row.formFields=result.pages[0].formFields;
    row.ocr=result.ocr;
    row.expectedText=fixture.expected;
    if (live) row.missingText=missingOcrText(fixture.expected, result.ocr?.text ?? '');
    if (fixture.fields) row.formMismatches=Object.entries(fixture.fields).filter(([name,val])=>{
      const field=result.pages[0].formFields.find(f=>f.name===name);
      const expected=String(val).replace(/^\//,'');
      return !field || JSON.stringify(field.value)!==JSON.stringify(field.type==='Ch' ? [expected] : expected) || field.status!=='stored_value';
    }).map(([name])=>name);
    row.status=live ? (row.missingText.length || row.formMismatches?.length ? 'review_required':'expected_text_matched') : 'prepared_without_ocr';
  } catch(error:any) {
    row.status='failed';row.errorCode=error.code??'TEST_FAILED';
  }
  row.wallMs=Math.round(performance.now()-start);
  if(wire) row.provider=wire;
  await writeFile(reportPath,JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({name:row.name,status:row.status,wallMs:row.wallMs,errorCode:row.errorCode,missingText:row.missingText,formMismatches:row.formMismatches}));
  // A provider contract/access failure is not permission to retry seven times.
  if(live && row.status==='failed') break;
}
console.log(JSON.stringify({report:reportPath,calls:report.calls}));
// Accuracy failures are release-gate failures, even when inference returned HTTP 200.
if(report.cases.length !== allowed.length || report.cases.some((c:any)=>c.status==='failed'||c.status==='review_required'||c.formMismatches?.length)) process.exitCode=1;
